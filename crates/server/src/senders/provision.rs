    type Seen = Arc<Mutex<Vec<(String, String, Value)>>>;

    /// A fake control API on loopback that answers each request by `answer(method, path)`;
    /// returns the client of it and what it received.
    async fn fake(answer: fn(&str, &str) -> (u16, Value)) -> (Control, Seen) {
        let seen: Seen = Arc::default();
        let recorder = Arc::clone(&seen);
        let app = axum::Router::new().fallback(move |request: axum::extract::Request| {
            let recorder = Arc::clone(&recorder);
            async move {
                let (parts, body) = request.into_parts();
                let body = axum::body::to_bytes(body, 65_536).await.unwrap_or_default();
                let json: Value = serde_json::from_slice(&body).unwrap_or(Value::Null);
                let (method, path) = (parts.method.to_string(), parts.uri.path().to_owned());
                let (status, reply) = answer(&method, &path);
                recorder.lock().unwrap().push((method, path, json));
                (StatusCode::from_u16(status).unwrap(), axum::Json(reply))
            }
        });
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let origin = format!("http://{}", listener.local_addr().unwrap());
        tokio::spawn(async move { axum::serve(listener, app).await });
        let secret = SecretString::from(format!(
            "whsec_{}",
            base64::engine::general_purpose::STANDARD.encode([7_u8; 32])
        ));
        (
            Control::new(Url::parse(&origin).unwrap(), &secret, false).unwrap(),
            seen,
        )
    }

    /// `acme.example` as the MTA renders it: verified or not, with its DKIM record once `key`.
    fn rendered(verified: bool, key: bool) -> Value {
        let mut records = vec![
            json!({
                "type": "TXT", "name": "_norbelys.acme.example",
                "content": "norbelys-verification=t", "note": "",
            }),
            json!({
                "type": "TXT", "name": "acme.example",
                "content": "v=spf1 ip4:192.0.2.10 ~all", "note": "Merge into existing SPF",
            }),
            json!({
                "type": "TXT", "name": "_dmarc.acme.example",
                "content": "v=DMARC1; p=none", "note": "Keep an existing DMARC policy",
            }),
            json!({
                "type": "MX", "name": "acme.example", "content": "mail.acme.example",
            }),
        ];
        if key {
            records.push(json!({
                "type": "TXT", "name": "norbelys._domainkey.acme.example",
                "content": "v=DKIM1; k=rsa; p=MIIB", "note": "",
            }));
        }
        json!({
            "name": "acme.example",
            "ownership_token": "norbelys-verification=t",
            "verified_at": verified.then_some("2026-10-02T00:00:00Z"),
            "dkim_selector": "norbelys",
            "dkim_public": key.then_some("MIIB"),
            "created_at": "2026-10-01T00:00:00Z",
            "records": records,
        })
    }

    /// The calls a fake received: method and path.
    fn calls(seen: &Seen) -> Vec<(String, String)> {
        seen.lock()
            .unwrap()
            .iter()
            .map(|(method, path, _)| (method.clone(), path.clone()))
            .collect()
    }

    /// A sending domain is registered with the very value its owner publishes for Norbelys,
    /// verified, and its SPF, DMARC and DKIM records read from what the MTA renders, preserving
    /// publication advice and excluding other records; a domain the MTA verified
    /// before is not verified again, and its key may still be pending; the MTA not seeing the
    /// record yet is an answer to wait on, while a refusal outside the contract is an error.
    #[tokio::test]
    async fn registers_and_verifies_a_domain() {
        fn fresh(_: &str, path: &str) -> (u16, Value) {
            match path {
                "/v1/domains" => (201, rendered(false, false)),
                _ => (200, rendered(true, true)),
            }
        }
        let (control, seen) = fake(fresh).await;
        assert_eq!(
            control
                .register_domain("acme.example", "norbelys-verification=t")
                .await
                .unwrap(),
            MtaDomain::Verified {
                spf: Some(MtaDnsRecord {
                    name: "acme.example".to_owned(),
                    value: "v=spf1 ip4:192.0.2.10 ~all".to_owned(),
                    note: "Merge into existing SPF".to_owned(),
                }),
                dmarc: Some(MtaDnsRecord {
                    name: "_dmarc.acme.example".to_owned(),
                    value: "v=DMARC1; p=none".to_owned(),
                    note: "Keep an existing DMARC policy".to_owned(),
                }),
                dkim: Some((
                    "norbelys._domainkey.acme.example".to_owned(),
                    "v=DKIM1; k=rsa; p=MIIB".to_owned()
                ))
            }
        );
        assert_eq!(
            calls(&seen),
            [
                ("POST".to_owned(), "/v1/domains".to_owned()),
                (
                    "POST".to_owned(),
                    "/v1/domains/acme.example/verify".to_owned()
                ),
            ]
        );
        assert_eq!(
            seen.lock().unwrap()[0].2,
            json!({ "name": "acme.example", "ownership_token": "norbelys-verification=t" })
        );

        fn known(_: &str, _: &str) -> (u16, Value) {
            (200, rendered(true, false))
        }
        let (control, seen) = fake(known).await;
        assert!(matches!(
            control
                .register_domain("acme.example", "norbelys-verification=t")
                .await
                .unwrap(),
            MtaDomain::Verified {
                spf: Some(_),
                dmarc: Some(_),
                dkim: None
            }
        ));
        assert_eq!(
            calls(&seen).len(),
            1,
            "a verified domain is not verified again"
        );

        fn unseen(_: &str, path: &str) -> (u16, Value) {
            match path {
                "/v1/domains" => (201, rendered(false, false)),
                _ => (
                    409,
                    json!({ "code": "conflict", "detail": "the TXT record does not hold the ownership token yet" }),
                ),
            }
        }
        let (control, _) = fake(unseen).await;
        assert_eq!(
            control
                .register_domain("acme.example", "norbelys-verification=t")
                .await
                .unwrap(),
            MtaDomain::Unverified(
                "the TXT record does not hold the ownership token yet".to_owned()
            )
        );

        fn refused(_: &str, _: &str) -> (u16, Value) {
            (
                422,
                json!({ "code": "validation_failed", "detail": "name must be a lowercase fully qualified domain name" }),
            )
        }
        let (control, _) = fake(refused).await;
        assert!(matches!(
            control
                .register_domain("acme.example", "norbelys-verification=t")
                .await,
            Err(ControlError::Answer { status: 422, .. })
        ));
    }

    /// The daily check of a `norbelys` connection reads its login on the MTA: enabled with a
    /// route, disabled, without a route, unknown, or an answer outside the contract.
    #[tokio::test]
    async fn reads_a_logins_state() {
        fn accounts(_: &str, path: &str) -> (u16, Value) {
            match path {
                "/v1/accounts/live@acme.example" => (
                    200,
                    json!({ "username": "live@acme.example", "route": "pwh_1", "disabled_at": null }),
                ),
                "/v1/accounts/off@acme.example" => (
                    200,
                    json!({ "username": "off@acme.example", "route": "pwh_1", "disabled_at": "2026-10-01T00:00:00Z" }),
                ),
                "/v1/accounts/mute@acme.example" => (
                    200,
                    json!({ "username": "mute@acme.example", "route": null, "disabled_at": null }),
                ),
                "/v1/accounts/boom@acme.example" => (500, json!({ "detail": "internal" })),
                _ => (404, json!({ "code": "not_found", "detail": "no account" })),
            }
        }
        let (control, _) = fake(accounts).await;
        for (username, expected) in [
            ("live@acme.example", LoginState::Active),
            ("off@acme.example", LoginState::Disabled),
            ("mute@acme.example", LoginState::Unrouted),
            ("gone@acme.example", LoginState::Missing),
        ] {
            assert_eq!(
                control.login(username).await.unwrap(),
                expected,
                "{username}"
            );
        }
        assert!(matches!(
            control.login("boom@acme.example").await,
            Err(ControlError::Answer { status: 500, .. })
        ));
    }
