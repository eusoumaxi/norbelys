//! `provider.norbelys.provision`: creates a `norbelys` connection's login on the managed MTA
//! through its control API, and registers where the MTA posts the login's evidence.
//!
//! # The control API
//!
//! The MTA's control service listens on the private network. Every request is signed per
//! Standard Webhooks (<https://www.standardwebhooks.com/>) with the per-installation secret
//! (`MTA_CONTROL_SECRET`, `whsec_` and the base64 of 24 to 64 bytes): `webhook-id` (fresh for
//! every request, retries included, since the service accepts an id once), `webhook-timestamp`
//! (Unix seconds) and `webhook-signature` (`v1,` and the base64 HMAC-SHA256 of
//! `id.timestamp.body`). Redirects are never followed, nothing is retried inside a call, and
//! errors come back as problem documents whose `detail` is shown on the connection.
//!
//! # The job
//!
//! 1. Read the connection (a `norbelys` connection in `verifying`) and its provider webhook.
//! 2. The login: when the MTA knows the address, a new password is issued for it; otherwise it is
//!    created (`kind` service for a domain, mailbox for a separate inbox; `rate_class` customer),
//!    which the MTA refuses unless the
//!    address's domain is registered and verified there. Either way the password is answered
//!    once and never stored by the MTA.
//! 3. The route: `PUT /v1/routes/{provider webhook}` with the webhook's URL, its Standard
//!    Webhooks secret (generated by Norbelys when the connection was created) and the login, so
//!    the MTA's evidence for this login arrives signed at this connection's webhook.
//! 4. Under the fence (the connection's credential version and status unchanged), the password
//!    is sealed through `set_connection_credential()`. A separate SMTP/IMAP check makes the
//!    connection active after the MTA has loaded the credential; API acceptance alone is not readiness.
//!
//! Every step can run again: a login that exists gets a new password (the one a lost answer
//! carried is replaced), and a route is replaced whole. So the kind is retried after a failure
//! like any external, repeatable call. A refusal the person must fix (the domain is not verified
//! on the MTA, the webhook URL is not one the MTA posts to) moves the connection to `failed` with
//! the MTA's words; `verify` runs the job again.

